/**
 * SQL que deja el catálogo de la papelería en una base de PRUEBA
 * (idempotente: PAP-001…). Lo usa e2e/papeleria.spec.js.
 */
export function sqlSembrar() {
  const q = (s) => s.replace(/'/g, "''");
  const cats = [...new Set(PAPELERIA.map((f) => f[1]))];
  const filas = PAPELERIA.map(([nombre, cat, unidad, precio], i) => {
    const metro = unidad === 'm';
    return `(N'PAP-${String(i + 1).padStart(3, '0')}', N'${q(nombre)}', ${precio}, ${metro ? 50 : 40}, N'${q(cat)}', ${metro ? 1 : 0}, ${metro ? "'m'" : "'pza'"}, ${Math.round(precio * 55) / 100})`;
  });
  return `
    IF NOT EXISTS (SELECT 1 FROM dbo.CAT_brands WHERE namee = N'Papelería') INSERT INTO dbo.CAT_brands (namee) VALUES (N'Papelería');
    ${cats.map((c) => `IF NOT EXISTS (SELECT 1 FROM dbo.CAT_categories WHERE namee = N'${q(c)}') INSERT INTO dbo.CAT_categories (namee) VALUES (N'${q(c)}');`).join('\n')}
    DECLARE @b INT = (SELECT id FROM dbo.CAT_brands WHERE namee = N'Papelería');
    DECLARE @f TABLE (pn NVARCHAR(40), nombre NVARCHAR(100), price DECIMAL(10,2), stock DECIMAL(10,2), cat NVARCHAR(100), granel BIT, uom NVARCHAR(10), cost DECIMAL(10,2));
    INSERT INTO @f VALUES ${filas.join(',\n')};
    INSERT INTO dbo.products (part_number, nombre, price, stock, active, sellable, inventory_mode, category_id, brand_id, cost, objeto_impuesto, tasa_iva, registrated_date, bar_code)
      SELECT f.pn, f.nombre, f.price, f.stock, 1, 1, 'DIRECT', c.id, @b, f.cost, '02', 0.16, GETDATE(), NULL
        FROM @f f JOIN dbo.CAT_categories c ON c.namee = f.cat
       WHERE NOT EXISTS (SELECT 1 FROM dbo.products p WHERE p.part_number = f.pn);
    UPDATE p SET p.price = f.price, p.stock = f.stock, p.allow_decimal_qty = f.granel, p.base_uom = f.uom, p.active = 1, p.sellable = 1
      FROM dbo.products p JOIN @f f ON f.pn = p.part_number;`;
}
